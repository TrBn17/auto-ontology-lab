"""Artifact writers for data/*.csv, data/_load.sql, manifest.json, .lab-dataset, and degraded_ack.json (§1.2, §1.3, §1.5)."""

from __future__ import annotations

import csv
from datetime import datetime, timezone
import hashlib
import io
import json
from pathlib import Path
from typing import Any

from lab.ddl import _quote_fqn, _quote_ident
from lab.generate import GenerationResult


def _format_pg_array_literal(items: list[Any]) -> str:
    """Format a Python list into a PostgreSQL array literal '{a,b}'."""
    parts: list[str] = []
    for item in items:
        if item is None:
            parts.append("NULL")
        else:
            s = str(item)
            if any(ch in s for ch in (',', '"', '\\', '{', '}', ' ')) or not s:
                escaped = s.replace("\\", "\\\\").replace('"', '\\"')
                parts.append(f'"{escaped}"')
            else:
                parts.append(s)
    return "{" + ",".join(parts) + "}"


def format_cell_for_csv(val: Any) -> str:
    """Format a cell value for PostgreSQL COPY CSV with NULL = \\N."""
    if val is None:
        return r"\N"
    if isinstance(val, bool):
        return "true" if val else "false"
    if isinstance(val, list):
        return _format_pg_array_literal(val)
    if isinstance(val, dict):
        return json.dumps(val, sort_keys=True)
    return str(val)


def serialize_table_csv(col_order: list[str], rows: list[dict[str, Any]], *, include_header: bool = True) -> str:
    """Serialize table rows to deterministic CSV text with \\n line endings and NULL = \\N."""
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
    if include_header:
        writer.writerow(col_order)
    for row in rows:
        writer.writerow([format_cell_for_csv(row.get(c)) for c in col_order])
    return buf.getvalue()


def compute_degraded_hash(degraded: list[dict[str, Any]]) -> str:
    """Compute a canonical SHA-256 digest of the degraded CHECK constraint list (§1.5)."""
    canonical = sorted(
        [
            {"table": str(item.get("table", "")), "constraint": str(item.get("constraint", ""))}
            for item in degraded
        ],
        key=lambda x: (x["table"], x["constraint"]),
    )
    payload = json.dumps(canonical, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def write_dataset_artifacts(
    out_dir: Path,
    profile: dict[str, Any],
    gen_result: GenerationResult,
    table_order: list[str],
    *,
    dataset_name: str | None = None,
    seed: int = 42,
    scale: float = 0.1,
) -> dict[str, Any]:
    """Write data/*.csv, data/_load.sql, manifest.json, and .lab-dataset."""
    out_dir.mkdir(parents=True, exist_ok=True)
    data_dir = out_dir / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    ds_name = dataset_name or out_dir.name
    tables_meta = profile.get("tables") or {}

    load_sql_blocks: list[str] = [
        "-- Auto-generated by lab clone (data/_load.sql)",
        "SET client_encoding = 'UTF8';",
        "SET standard_conforming_strings = on;",
        "",
    ]

    # Write per-table CSVs and inline COPY blocks in topological table_order
    for table_fqn in table_order:
        col_order = gen_result.column_order_by_table.get(table_fqn, [])
        rows = gen_result.rows_by_table.get(table_fqn, [])
        csv_with_header = serialize_table_csv(col_order, rows, include_header=True)
        csv_path = data_dir / f"{table_fqn}.csv"
        csv_path.write_bytes(csv_with_header.encode("utf-8"))

        if rows and col_order:
            cols_sql = ", ".join(_quote_ident(c) for c in col_order)
            csv_body = serialize_table_csv(col_order, rows, include_header=False)
            load_sql_blocks.append(
                f"COPY {_quote_fqn(table_fqn)} ({cols_sql}) FROM stdin WITH (FORMAT csv, NULL '\\N');\n"
                f"{csv_body}\\.\n"
            )

            # Advance sequences for identity / serial columns
            t_cols_meta = tables_meta.get(table_fqn, {}).get("columns") or {}
            for c in col_order:
                if t_cols_meta.get(c, {}).get("is_identity"):
                    load_sql_blocks.append(
                        f"SELECT setval(pg_get_serial_sequence('{table_fqn}', '{c}'), "
                        f"COALESCE((SELECT MAX({_quote_ident(c)}) FROM {_quote_fqn(table_fqn)}), 1), true);"
                    )

    (data_dir / "_load.sql").write_bytes(("\n".join(load_sql_blocks) + "\n").encode("utf-8"))

    # Build manifest.json (§1.3) in deterministic topological table_order
    entities: list[dict[str, Any]] = []
    row_counts: dict[str, int] = {}
    for table_fqn in table_order:
        if table_fqn not in tables_meta:
            continue
        pk_cols = list(tables_meta[table_fqn].get("pk") or [])
        cnt = len(gen_result.rows_by_table.get(table_fqn, []))
        row_counts[table_fqn] = cnt
        entities.append(
            {
                "table": table_fqn,
                "pk": pk_cols,
                "row_count": cnt,
            }
        )

    relationships: list[dict[str, Any]] = []
    for fk in profile.get("foreign_keys") or []:
        relationships.append(
            {
                "kind": fk.get("kind", "fk"),
                "from": {
                    "table": fk["from"]["table"],
                    "columns": list(fk["from"]["columns"]),
                },
                "to": {
                    "table": fk["to"]["table"],
                    "columns": list(fk["to"]["columns"]),
                },
            }
        )

    manifest = {
        "dataset": ds_name,
        "load_order": [
            "ddl/01_types.sql",
            "ddl/02_tables.sql",
            "data/_load.sql",
            "ddl/03_fkeys.sql",
            "ddl/04_views.sql",
        ],
        "row_counts": row_counts,
        "entities": entities,
        "relationships": relationships,
        "degraded": gen_result.degraded_checks,
        "repaired_checks": gen_result.repaired_checks,
        "semantic": {},
    }
    (out_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=False) + "\n",
        encoding="utf-8",
    )

    # Marker file .lab-dataset (§1.2)
    profile_bytes = json.dumps(profile, sort_keys=True).encode("utf-8")
    profile_hash = hashlib.sha256(profile_bytes).hexdigest()
    marker = {
        "dataset_id": ds_name,
        "seed": seed,
        "scale": scale,
        "profile_sha256": profile_hash,
    }
    (out_dir / ".lab-dataset").write_text(
        json.dumps(marker, indent=2) + "\n",
        encoding="utf-8",
    )

    return manifest


def acknowledge_degraded_checks(out_dir: Path, reviewer: str) -> dict[str, Any]:
    """Acknowledge degraded CHECK constraints and write degraded_ack.json (§1.5)."""
    reviewer_clean = reviewer.strip()
    if not reviewer_clean:
        raise ValueError("Reviewer name cannot be empty.")

    manifest_path = out_dir / "manifest.json"
    if not manifest_path.is_file():
        raise FileNotFoundError(f"manifest.json not found in {out_dir}")

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    degraded = manifest.get("degraded") or []
    deg_hash = compute_degraded_hash(degraded)

    ack_payload = {
        "dataset": manifest.get("dataset", out_dir.name),
        "reviewer": reviewer_clean,
        "acknowledged_at": datetime.now(timezone.utc).isoformat(),
        "degraded_sha256": deg_hash,
        "degraded": degraded,
    }
    (out_dir / "degraded_ack.json").write_text(
        json.dumps(ack_payload, indent=2) + "\n",
        encoding="utf-8",
    )
    return ack_payload


def is_degraded_ack_valid(out_dir: Path, degraded: list[dict[str, Any]]) -> bool:
    """Return True if degraded_ack.json exists, has a non-empty reviewer, and matches the degraded hash."""
    ack_path = out_dir / "degraded_ack.json"
    if not ack_path.is_file():
        return False
    try:
        ack = json.loads(ack_path.read_text(encoding="utf-8"))
    except Exception:
        return False
    if not str(ack.get("reviewer", "")).strip():
        return False
    return ack.get("degraded_sha256") == compute_degraded_hash(degraded)
